#!/usr/bin/env python3
"""Fetch Material Symbols Rounded (Apache-2.0) as Android vector drawables for BumBoard.

Reads icons.txt and writes bumboard/app/res/drawable/<name>.xml (weight 400, grade 0, 24 dp,
white fill — tinted by code). Names that match an upstream drawable replace it, because
BumBoard's res directory has priority over upstream's (see HANDOFF.md).
"""
import pathlib, re, sys, urllib.request

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "app/res/drawable"
UPSTREAM = HERE.parent / "upstream/fcitx5-android/app/src/main/res/drawable"
BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android"


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    failed = []
    for line in (HERE / "icons.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        name, symbol = [s.strip() for s in line.split("=")]
        symbol, _, style = symbol.partition(":")
        suffix = "_fill1_24px" if style == "fill" else "_24px"
        try:
            xml = fetch(f"{BASE}/{symbol}/materialsymbolsrounded/{symbol}{suffix}.xml")
        except Exception as e:
            failed.append(f"{name} = {symbol}{suffix}: {e}")
            continue
        xml = re.sub(r'\s*android:tint="[^"]*"', "", xml)
        xml = re.sub(r'android:fillColor="[^"]*"', 'android:fillColor="#ffffff"', xml)
        up = UPSTREAM / f"{name}.xml"
        mirrored = up.exists() and 'autoMirrored="true"' in up.read_text()
        if mirrored and "autoMirrored" not in xml:
            xml = xml.replace("<vector ", '<vector android:autoMirrored="true" ', 1)
        header = f"<!-- Material Symbols Rounded \"{symbol}\"{' (filled)' if style == 'fill' else ''}, Apache-2.0. Generated by bumboard/tools/icons.py -->\n"
        (OUT / f"{name}.xml").write_text(header + xml.strip() + "\n")
    if failed:
        print("failed:\n  " + "\n  ".join(failed), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
